-- Builds the English translation manifest from the mission data and strings.lua.
--
--   lua tools/gen_l10n.lua            rewrite scripts/guidedmissions/languages/en.lua
--   lua tools/gen_l10n.lua --check    fail if the file is stale or hand-edited
--
-- Run from any directory; paths are resolved from this script's location.
-- English is the source language, so every value in en.lua equals its key. The
-- file is the translator template and the coverage baseline; the other locale
-- tables use the same keys with translated values.

local script_path = arg[0] or "tools/gen_l10n.lua"
local root = script_path:match("^(.*)[/\\]tools[/\\][^/\\]+$") or "."
package.path = root .. "/scripts/?.lua;" .. package.path

local Missions = require("guidedmissions/missions")
local Emergencies = require("guidedmissions/emergencies")
local Strings = require("guidedmissions/strings")

local OUTPUT = root .. "/scripts/guidedmissions/languages/en.lua"

local function CheckSource(where, text)
    if type(text) ~= "string" then
        error(where .. " is not a string", 0)
    end
    if #text == 0 then
        error(where .. " is empty", 0)
    end
    if text:find("[|;\"\r\n]") ~= nil then
        error(where .. " contains a reserved character (| ; quote or newline): " .. text, 0)
    end
end

local keys = {}
local seen = {}

local function Add(where, text)
    if text == nil then
        return
    end
    CheckSource(where, text)
    if not seen[text] then
        seen[text] = true
        keys[#keys + 1] = text
    end
end

local function AddObjectives(where, objectives)
    for i, objective in ipairs(objectives or {}) do
        Add(where .. " objective " .. i .. " label", objective.label)
    end
end

for i, mission in ipairs(Missions) do
    local where = "mission " .. i .. " (" .. tostring(mission.id) .. ")"
    Add(where .. " title", mission.title)
    Add(where .. " subtext", mission.subtext)
    Add(where .. " hint", mission.hint)
    AddObjectives(where, mission.objectives)
end

for i, entry in ipairs(Emergencies.entries or {}) do
    local where = "emergency " .. i .. " (" .. tostring(entry.id) .. ")"
    Add(where .. " title", entry.title)
    Add(where .. " subtext", entry.subtext)
    Add(where .. " resolved_subtext", entry.resolved_subtext)
    Add(where .. " hint", entry.hint)
    AddObjectives(where, entry.objectives)
end

for name, value in pairs(Strings) do
    if type(value) == "string" then
        Add("Strings." .. name, value)
    end
end

table.sort(keys)

local lines = {
    "-- English source manifest. GENERATED by tools/gen_l10n.lua; do not hand-edit.",
    "-- Keys are the authored source strings; values are the English rendering.",
    "-- Because English is the source language every value equals its key.",
    "-- This file is the translator template and the coverage baseline; a missing",
    "-- locale file or key falls back to the source string at runtime.",
    "-- Encoding: UTF-8, no BOM.",
    "return {",
}
for _, key in ipairs(keys) do
    lines[#lines + 1] = "    [" .. string.format("%q", key) .. "] = "
        .. string.format("%q", key) .. ","
end
lines[#lines + 1] = "}"
lines[#lines + 1] = ""

local expected = table.concat(lines, "\n")

if arg[1] == "--check" then
    local file = io.open(OUTPUT, "rb")
    if file == nil then
        print("l10n manifest missing: " .. OUTPUT)
        os.exit(1)
    end
    local actual = file:read("*a")
    file:close()

    if actual == expected then
        print("l10n manifest is up to date (" .. #keys .. " strings)")
        os.exit(0)
    end

    local function KeySet(text)
        local set = {}
        for key in text:gmatch("%[\"(.-)\"%]") do
            set[key] = true
        end
        return set
    end

    local want = KeySet(expected)
    local have = KeySet(actual)
    for key in pairs(want) do
        if not have[key] then
            print("missing from en.lua: " .. key)
        end
    end
    for key in pairs(have) do
        if not want[key] then
            print("stale in en.lua: " .. key)
        end
    end
    print("l10n manifest is stale; run lua tools/gen_l10n.lua")
    os.exit(1)
end

local file = io.open(OUTPUT, "wb")
if file == nil then
    print("cannot write " .. OUTPUT)
    os.exit(1)
end
file:write(expected)
file:close()
print("wrote " .. OUTPUT .. " (" .. #keys .. " strings)")
